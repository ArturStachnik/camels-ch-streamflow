"""Write the configurations of setting 3 (data-scarce basins).

For each basin of splits/setting3/sample.csv and each record length N in FINETUNE_YEARS,
the training data are the last N hydrological years of the training period of that basin.
Two ways of using them:

- fine-tune: start from the setting-2 model of the fold in which the basin was a test
  basin, so the starting model has never seen this basin or any basin upstream or
  downstream of it. LSTM and head are trained, with the scaler of the starting model.
- from scratch: a new LSTM trained on this basin only, with the five forcing variables
  (static attributes are constant within one basin and are left out).

Both are evaluated once on the test period. The recipes are fixed in advance and not
tuned: a fixed number of weight updates, independent of N, so that short records do not
get fewer updates.

Usage:
  python scripts/make_setting3_configs.py scratch
  python scripts/make_setting3_configs.py finetune     # for every fold whose setting-2 model is finished
"""
import math
import sys
from pathlib import Path

import pandas as pd
from ruamel.yaml import YAML

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "configs/setting3"
FINETUNE_YEARS = (1, 2, 5)
BATCH = 256
SCRATCH = dict(updates=1500, hidden_size=64, learning_rate=1e-3, seed=401)
FINETUNE = dict(updates=300, learning_rate=1e-4, seed=501)


def fold_run(k):
    """Folder with the final (epoch 30) weights of setting-2 fold k: the run itself, or the
    continue_training subfolder if the run was interrupted and resumed."""
    hits = sorted(ROOT.glob(f"runs/setting2_fold{k}_*/model_epoch030.pt")) +         sorted(ROOT.glob(f"runs/setting2_fold{k}_*/continue_training_from_epoch*/model_epoch030.pt"))
    return hits[-1].parent if hits else None


def n_batches(years):
    return math.ceil(round(years * 365.25) / BATCH)


def window(years, periods):
    end = pd.Timestamp(periods["train"][1])
    start = end - pd.DateOffset(years=years) + pd.Timedelta(days=1)
    return start.strftime("%d/%m/%Y"), end.strftime("%d/%m/%Y")


def common(basin, years, periods, epochs):
    start, end = window(years, periods)
    fmt = lambda s: pd.Timestamp(s).strftime("%d/%m/%Y")
    return {
        "train_basin_file": f"splits/setting3/basin_{basin}.txt",
        "validation_basin_file": f"splits/setting3/basin_{basin}.txt",
        "test_basin_file": f"splits/setting3/basin_{basin}.txt",
        "train_start_date": start, "train_end_date": end,
        "validation_start_date": fmt(periods["validation"][0]), "validation_end_date": fmt(periods["validation"][1]),
        "test_start_date": fmt(periods["test"][0]), "test_end_date": fmt(periods["test"][1]),
        "epochs": epochs, "save_weights_every": epochs, "validate_every": None,
        "log_interval": 10_000, "batch_size": BATCH, "run_dir": "runs/setting3",
    }


def dump(cfg, path, header):
    yaml = YAML()
    yaml.default_flow_style = None
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        yaml.dump(cfg, f)


def main():
    mode = sys.argv[1]
    yaml = YAML(typ="safe")
    periods = {k: [str(pd.Timestamp(d).date()) for d in v] for k, v in yaml.load((ROOT / "splits/periods.yml").read_text()).items()}
    sample = pd.read_csv(ROOT / "splits/setting3/sample.csv", dtype={"gauge_id": str})
    base = yaml.load((ROOT / "configs/baseline_seed1.yml").read_text())
    OUT.mkdir(parents=True, exist_ok=True)
    for row in sample.itertuples():
        for years in FINETUNE_YEARS:
            if mode == "scratch":
                epochs = math.ceil(SCRATCH["updates"] / n_batches(years))
                cfg = {k: v for k, v in base.items() if k != "static_attributes"}
                cfg.update(common(row.gauge_id, years, periods, epochs))
                cfg.update(experiment_name=f"scratch_{row.gauge_id}_{years}y", hidden_size=SCRATCH["hidden_size"],
                           learning_rate={0: SCRATCH["learning_rate"]}, seed=SCRATCH["seed"])
                header = (f"# Setting 3, from scratch: basin {row.gauge_id} ({row.regime}), last {years} training year(s).\n"
                          f"# Single-basin LSTM, forcing only, {SCRATCH['updates']} weight updates. Generated by scripts/make_setting3_configs.py.\n")
            else:
                run = fold_run(row.fold)
                if run is None or not (run / "test/model_epoch030/test_results.p").exists():
                    continue  # the starting model of this fold is not finished yet
                epochs = math.ceil(FINETUNE["updates"] / n_batches(years))
                cfg = common(row.gauge_id, years, periods, epochs)
                cfg.update(experiment_name=f"finetune_{row.gauge_id}_{years}y", base_run_dir=run.relative_to(ROOT).as_posix(),
                           finetune_modules=["lstm", "head"], learning_rate={0: FINETUNE["learning_rate"]}, seed=FINETUNE["seed"])
                header = (f"# Setting 3, fine-tuned: basin {row.gauge_id} ({row.regime}), last {years} training year(s).\n"
                          f"# Starts from the setting-2 model of fold {row.fold}, in which this basin was a test basin.\n"
                          f"# {FINETUNE['updates']} weight updates. Generated by scripts/make_setting3_configs.py.\n")
            dump(cfg, OUT / f"{cfg['experiment_name']}.yml", header)
    print(f"wrote {mode} configs for {len(sample)} basins x {len(FINETUNE_YEARS)} record lengths")


if __name__ == "__main__":
    main()
